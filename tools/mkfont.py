# A handful of drawing characters the UI wants, mapped into the control-code
# range so they never collide with printable ASCII.
EXTRAS = {
    0x01: "..#.. .###. ##### ##### ##### .###. ..#.. ..... .....",  # diamond / logo mark
    0x02: "##### #...# #.#.# #...# #.#.# #...# ##### ..... .....",  # chip
    0x03: "..... .#.#. ..... #...# ..... .#.#. ..... ..... .....",  # dither
    0x04: "##### ##### ##### ##### ##### ##### ##### ..... .....",  # solid block
    0x05: "#.#.# .#.#. #.#.# .#.#. #.#.# .#.#. #.#.# ..... .....",  # 50% block
    0x06: "..#.. .###. ##### .###. ..#.. ..... ..... ..... .....",  # bullet diamond
    0x07: "#.... ##... ###.. ####. ###.. ##... #.... ..... .....",  # right arrow
    0x08: "....# ...## ..### .#### ..### ...## ....# ..... .....",  # left arrow
    0x0E: "..#.. .###. ##### ..#.. ..#.. ..#.. ..#.. ..... .....",  # up arrow
    0x0F: "..#.. ..#.. ..#.. ..#.. ##### .###. ..#.. ..... .....",  # down arrow
}


def render(pattern):
    """Turn a 9x5 pattern into 16 rows of 8-bit values."""
    rows = pattern.split()
    if len(rows) != GLYPH_ROWS:
        raise ValueError(f"expected {GLYPH_ROWS} rows, got {len(rows)}: {pattern!r}")

    cell = [0] * CELL_HEIGHT
    for index, row in enumerate(rows):
        if len(row) != 5:
            raise ValueError(f"expected 5 columns, got {len(row)}: {row!r}")
        bits = 0
        for column, pixel in enumerate(row):
            if pixel == "#":
                # Bit 7 is the leftmost pixel; one column of left bearing.
                bits |= 1 << (7 - (column + 1))
            elif pixel != ".":
                raise ValueError(f"unexpected pixel {pixel!r}")
        cell[GLYPH_TOP + index] = bits
    return cell


def main():
    table = [[0] * CELL_HEIGHT for _ in range(256)]

    for char, pattern in GLYPHS.items():
        table[ord(char)] = render(pattern)
    for code, pattern in EXTRAS.items():
        table[code] = render(pattern)

    # Anything undrawn renders as a hollow box, so missing glyphs are visible
    # rather than silently blank.
    missing = render("..... ##### #...# #...# #...# ##### ..... ..... .....")
    for code in range(256):
        if all(value == 0 for value in table[code]) and code != ord(" "):
            table[code] = missing

    out = sys.stdout
    out.write("//! HALCYON's console font — generated by tools/mkfont.py.\n")
    out.write("//!\n")
    out.write("//! Do not edit by hand: change the glyph art in the generator and\n")
    out.write("//! re-run it. The letterforms are drawn for this system, so the font\n")
    out.write("//! carries no third-party licensing.\n")
    out.write("//!\n")
    out.write(f"//! {CELL_WIDTH}x{CELL_HEIGHT} cell, {GLYPH_ROWS}-row drawing area starting at row {GLYPH_TOP}.\n")
    out.write("\n")
    out.write(f"pub const GLYPH_WIDTH: usize = {CELL_WIDTH};\n")
    out.write(f"pub const GLYPH_HEIGHT: usize = {CELL_HEIGHT};\n")
    out.write("\n")
    out.write("/// One byte per scanline; bit 7 is the leftmost pixel.\n")
    out.write(f"pub static FONT: [[u8; {CELL_HEIGHT}]; 256] = [\n")
    for code in range(256):
        values = ", ".join(f"0x{value:02X}" for value in table[code])
        label = chr(code) if 33 <= code <= 126 else ""
        comment = f" // {code:3} {label}" if label else f" // {code:3}"
        out.write(f"    [{values}],{comment}\n")
    out.write("];\n")


if __name__ == "__main__":
    main()
